#!/usr/bin/env python3
"""Open one GitHub Issue per high-priority, unreviewed detection.
A detection is NOT confirmation that a race rule or registration date changed.
"""
import json
import os
import sys
from pathlib import Path
from urllib.request import Request, urlopen
from urllib.parse import quote
from urllib.error import HTTPError, URLError

ROOT = Path(__file__).resolve().parents[1]
HISTORY = ROOT / "data" / "monitor-history.json"
REGISTRY = ROOT / "data" / "race-monitor.json"

def main():
    token = os.getenv("GITHUB_TOKEN")
    repo = os.getenv("GITHUB_REPOSITORY")
    if not token or not repo:
        raise SystemExit("GITHUB_TOKEN or GITHUB_REPOSITORY missing")
    history = json.loads(HISTORY.read_text(encoding="utf-8"))
    registry = json.loads(REGISTRY.read_text(encoding="utf-8"))
    names = {e["id"]: e["name"] for e in registry.get("events", [])}
    created = 0
    failed = 0
    test_mode = os.getenv("TRAILRACE_TEST_NOTIFICATION") == "1"
    if test_mode:
        history = {"events": [{"raceId": "trailrace_test", "detectedAt": "2026-11-17T00:00:00+00:00", "status": "needs_review", "sourceUrl": "https://github.com/" + repo, "categories": [{"category": "registration_open", "priority": "high"}]}]}
        names["trailrace_test"] = "TrailRace TEST ONLY (not a real race)"

    for event in history.get("events", []):
        if event.get("status") != "needs_review" or event.get("issueNumber"):
            continue
        categories = event.get("categories") or []
        # Do not issue notifications for generic/unclassified text changes.
        if not any(c.get("priority") == "high" and c.get("category") not in ("unclassified_change", "other_page_text") for c in categories):
            continue
        race = names.get(event.get("raceId"), event.get("raceId", "Unknown"))
        topics = ", ".join(c.get("category", "unknown") for c in categories)
        title = f"[Needs review] {race}: potential registration-related page change"
        if test_mode:
            title = "[TEST ONLY] TrailRace notification and deduplication check"
            query = quote("repo:" + repo + ' is:issue in:title "[TEST ONLY] TrailRace notification and deduplication check"')
            search_req = Request("https://api.github.com/search/issues?q=" + query, headers={"Authorization": f"Bearer {token}", "Accept": "application/vnd.github+json", "User-Agent": "TrailRaceMonitor/0.1"})
            with urlopen(search_req, timeout=20) as response:
                found = json.load(response)
            if found.get("total_count", 0):
                print("TEST: existing issue found, skipped duplicate creation.")
                continue
        added = event.get("addedEvidenceSnippets") or []
        removed = event.get("removedEvidenceSnippets") or []
        evidence = "\n### Automatically extracted differences (UNVERIFIED)\n" + ("\n".join("- Added: " + str(v)[:320] for v in added[:8]) if added else "- No precise added text available") + "\n" + ("\n".join("- Removed: " + str(v)[:320] for v in removed[:8]) if removed else "- No precise removed text available") + "\n"
        body = (
            "## Automated detection — NOT an official announcement\n\n"
            f"- Race: {race}\n"
            f"- Detected (UTC): {event.get('detectedAt', 'unknown')}\n"
            f"- Possible topics (keyword hints only): {topics}\n"
            f"- Source: {event.get('sourceUrl', '')}\n\n"
            "### Human verification checklist\n"
            "- [ ] Open the official source and locate the specific announcement.\n"
            "- [ ] Check event year, distance/category, dates, timezone, and eligibility.\n"
            "- [ ] Compare with previous official terms; ignore navigation/marketing changes.\n"
            "- [ ] Mark verified or false positive manually; do not publish unverified claims.\n\n"
            "This Issue was generated by TrailRace's page text monitor. "
            "It is not a confirmed registration opening, deadline, or lottery change.\n"
        )
        if test_mode:
            body = "**TEST ONLY — SYNTHETIC DATA. NO REAL RACE ANNOUNCEMENT.**\n\n" + body
        payload = json.dumps({"title": title, "body": body}).encode("utf-8")
        req = Request(
            f"https://api.github.com/repos/{repo}/issues",
            data=payload,
            headers={"Authorization": f"Bearer {token}", "Accept": "application/vnd.github+json", "Content-Type": "application/json", "X-GitHub-Api-Version": "2022-11-28", "User-Agent": "TrailRaceMonitor/0.1"},
            method="POST",
        )
        try:
            with urlopen(req, timeout=20) as response:
                result = json.load(response)
        except (HTTPError, URLError, TimeoutError) as error:
            print(f"Issue creation failed for {race}: {type(error).__name__}", file=sys.stderr)
            failed += 1
            continue
        if test_mode:
            print(f"TEST: created Issue #{result['number']} — {result['html_url']}")
            created += 1
            continue
        event["issueNumber"] = result["number"]
        event["issueUrl"] = result["html_url"]
        created += 1
        # Save immediately so later failures do not lose dedup state.
        HISTORY.write_text(json.dumps(history, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"Created {created} high-priority review Issues; failures: {failed}.")
    if failed:
        raise SystemExit("Some review Issues could not be created; retry required.")

if __name__ == "__main__":
    main()
